import { mkdir, writeFile, access, unlink, copyFile, readdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { KokoroTTS } from 'kokoro-js';
import { stationGreeting, stationReply } from '../packages/shared/dist/station.js';
import { tutorialText } from '../apps/game/src/speech/tutorial-text.ts';

const directory = new URL('../apps/game/assets/audio/station/', import.meta.url);
await mkdir(directory, { recursive: true });
const texts = new Set([tutorialText]);
for (const npc of ['npc_station_information', 'npc_passenger_backpack', 'npc_passenger_suitcase']) {
  texts.add(stationGreeting(npc).text);
  for (const step of [0, 1, 2]) for (const input of ['hello', 'where can I get an ID card', 'goodbye', 'thank you', 'other']) texts.add(stationReply(npc, step, input).text);
}
const tts = await KokoroTTS.from_pretrained('onnx-community/Kokoro-82M-v1.0-ONNX', { dtype: 'q8', device: 'cpu', cache_dir: new URL('../.voice-cache/', import.meta.url).pathname.replace(/^\/(\w:)/, '$1') });
const entries = [];
const previous = new Map();
try {
  const oldManifest = JSON.parse(await (await import('node:fs/promises')).readFile(new URL('../apps/game/assets/audio/station/manifest.json', import.meta.url), 'utf8'));
  for (const entry of oldManifest) previous.set(`${entry.voice}:${entry.text}`, entry.file);
} catch { /* First generation has no manifest to reuse. */ }
const require = createRequire(import.meta.url);
const ffmpeg = process.env.FFMPEG_PATH ?? join(dirname(require.resolve('@ffmpeg-installer/win32-x64/package.json')), 'ffmpeg.exe');
for (const [line, text] of [...texts].entries()) for (const [gender, voice] of [['female', 'af_heart'], ['male', 'am_michael']]) {
  const id = createHash('sha256').update(`${voice}:${text}`).digest('hex').slice(0, 16);
  const filename = `line-${String(line + 1).padStart(2, '0')}-${gender}.mp3`;
  const file = new URL(filename, directory);
  const wave = new URL(`${id}.wav`, directory);
  const localPath = (url) => url.pathname.replace(/^\/(\w:)/, '$1');
  try { await access(file); } catch {
    const oldName = previous.get(`${voice}:${text}`);
    if (oldName) try { await copyFile(new URL(oldName, directory), file); } catch { /* Regenerate when no prior clip remains. */ }
  }
  try { await access(file); } catch {
    try { await access(wave); } catch {
      console.log(`Generating ${gender}: ${text.slice(0, 45)}`);
      const audio = await tts.generate(text, { voice, speed: 0.95 });
      await audio.save(localPath(wave));
    }
    execFileSync(ffmpeg, ['-y', '-i', localPath(wave), '-ac', '1', '-b:a', '64k', localPath(file)], { stdio: 'ignore', windowsHide: true });
    await unlink(wave);
  }
  entries.push({ id: `line-${String(line + 1).padStart(2, '0')}`, text, gender, voice, file: filename });
}
await writeFile(new URL('manifest.json', directory), JSON.stringify(entries, null, 2) + '\n');
await writeFile(new URL('../apps/game/src/speech/station-audio.ts', import.meta.url), '// Generated by pnpm voices:build. Do not edit manually.\n' + entries.map((entry, index) => `import clip${index} from '../../assets/audio/station/${entry.file}';`).join('\n') + '\nexport const stationAudio = [\n' + entries.map((entry, index) => `  { text: ${JSON.stringify(entry.text)}, gender: '${entry.gender}', asset: clip${index} },`).join('\n') + '\n] as const;\n');
for (const old of await readdir(new URL('../apps/game/assets/audio/station/', import.meta.url))) {
  if (/^[a-f\d]{16}\.mp3$/i.test(old)) await unlink(new URL(old, directory));
}
console.log(`Ready: ${entries.length} recordings.`);
