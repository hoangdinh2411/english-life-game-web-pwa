import { access, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const rootArgumentIndex = process.argv.indexOf('--root');
const root = rootArgumentIndex === -1 ? resolve(import.meta.dirname, '..') : resolve(process.argv[rootArgumentIndex + 1] ?? '');
const catalogPath = resolve(root, 'apps/game/assets/flags/countries.json');
const migrationPath = resolve(root, 'supabase/migrations/032_country_clock_worlds.sql');

function fail(message) {
  throw new Error(`apps/game/assets/flags/countries.json: ${message}`);
}

function sql(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

async function loadCountries() {
  const countries = JSON.parse(await readFile(catalogPath, 'utf8'));
  if (!Array.isArray(countries) || countries.length !== 247) fail('expected exactly 247 countries');
  const ids = new Set();
  const isoCodes = new Set();
  for (const [index, country] of countries.entries()) {
    if (typeof country !== 'object' || country === null || Array.isArray(country)) fail(`${index}: invalid country`);
    if (typeof country.id !== 'string' || !/^country_[a-z0-9_]+$/.test(country.id)) fail(`${index}.id: invalid id`);
    if (ids.has(country.id)) fail(`${index}.id: duplicate id ${country.id}`);
    ids.add(country.id);
    if (typeof country.name !== 'string' || country.name.trim() !== country.name || country.name.length === 0) fail(`${index}.name: invalid name`);
    if (typeof country.iso !== 'string' || !/^[A-Z]{2}$/.test(country.iso)) fail(`${index}.iso: invalid ISO code`);
    if (isoCodes.has(country.iso)) fail(`${index}.iso: duplicate ISO code ${country.iso}`);
    isoCodes.add(country.iso);
    if (!Array.isArray(country.allTimeZones) || country.allTimeZones.length === 0 || !country.allTimeZones.includes(country.timeZone)) {
      fail(`${index}.timeZone: primary zone must belong to allTimeZones`);
    }
    for (const zone of country.allTimeZones) {
      try { new Intl.DateTimeFormat('en', { timeZone: zone }).format(); }
      catch { fail(`${index}.allTimeZones: invalid IANA zone ${zone}`); }
    }
    const iso = country.iso.toLowerCase();
    if (country.flagSvg !== `flags/svg/${iso}.svg` || country.flagPng !== `flags/png/${iso}.png`) {
      fail(`${index}: flag paths must match the ISO code`);
    }
    await access(resolve(root, 'apps/game/assets', country.flagSvg));
    await access(resolve(root, 'apps/game/assets', country.flagPng));
  }
  return countries;
}

function renderMigration(countries) {
  const values = countries.map(country =>
    `  (${sql(country.id)}, ${sql(country.name)}, ${sql(country.iso)}, ${sql(country.timeZone)}, 'city_maplewood', 'loc_station')`,
  ).join(',\n');
  return `-- Generated by scripts/generate-country-worlds-migration.mjs. Do not edit by hand.
-- The migration is self-contained: deployed databases never read repository assets.

insert into public.cities (id, name, description)
values ('city_maplewood', 'Starter City', 'The generic starter city.')
on conflict (id) do nothing;

insert into public.locations (id, city_id, name, type)
values ('loc_station', 'city_maplewood', 'Train Station', 'station')
on conflict (id) do nothing;

alter table public.countries
  add column starter_location_id text references public.locations(id);

alter table public.countries drop column flag;

insert into public.countries (id, name, iso_code, time_zone, starter_city_id, starter_location_id)
values
${values}
on conflict (id) do update set
  name = excluded.name,
  iso_code = excluded.iso_code,
  time_zone = excluded.time_zone,
  starter_city_id = excluded.starter_city_id,
  starter_location_id = excluded.starter_location_id;

alter table public.countries alter column starter_location_id set not null;

create table public.worlds (
  id              uuid primary key default gen_random_uuid(),
  country_id      text not null unique references public.countries(id),
  clock_start_utc timestamptz not null default clock_timestamp(),
  clock_rate      integer not null default 6 check (clock_rate = 6),
  created_at      timestamptz not null default now()
);

create function public.worlds_block_clock_identity_update()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.country_id is distinct from old.country_id
    or new.clock_start_utc is distinct from old.clock_start_utc
    or new.clock_rate is distinct from old.clock_rate then
    raise exception 'world country and clock fields are immutable';
  end if;
  return new;
end;
$$;

create trigger worlds_clock_identity_immutable
  before update on public.worlds
  for each row execute function public.worlds_block_clock_identity_update();

alter table public.characters add column world_id uuid references public.worlds(id);

insert into public.worlds (country_id)
select distinct country_id from public.characters where country_id is not null
on conflict (country_id) do nothing;

update public.characters characters
set world_id = worlds.id
from public.worlds worlds
where characters.country_id = worlds.country_id
  and characters.world_id is null;

alter table public.worlds enable row level security;
`;
}

const countries = await loadCountries();
const output = renderMigration(countries);
if (process.argv.includes('--check')) {
  const committed = await readFile(migrationPath, 'utf8').catch(() => '');
  if (committed !== output) throw new Error('032_country_clock_worlds.sql is not deterministic or is out of date');
} else {
  await writeFile(migrationPath, output);
}

process.stdout.write(`Validated ${countries.length} countries and generated a deterministic migration.\n`);
